def motivation_for(day: date, outbox: Path) -> str:
    path = outbox / f"motivation_{day.isoformat()}.md"
    if path.exists():
        text = path.read_text(encoding="utf-8").strip()
        if text:
            return text
    return MOTIVATION_POOL[day.toordinal() % len(MOTIVATION_POOL)]
